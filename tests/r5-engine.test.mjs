import assert from 'node:assert/strict';
import {geometryFromMask,containsWorld} from '../engine/glyph-geometry.mjs';
import {contactManifold,outwardNormal} from '../engine/shape-contact-v5.mjs';
import {ShapeSimulationV5,SHAPE_SIM_VERSION,SHAPE_RULE_VERSION} from '../engine/shape-sim-v5.mjs';
import {LEVEL_CATALOG,isUnlocked,evaluateLevelResult} from '../engine/level-catalog.mjs';
import {emptySave,loadSave,commitBattle,SAVE_KEY} from '../engine/r5-local-save.mjs';
const N=40,gen=fn=>{const m=new Uint8Array(N*N);for(let y=0;y<N;y++)for(let x=0;x<N;x++)m[y*N+x]=Number(fn(x,y));return m;};
const block=geometryFromMask(gen((x,y)=>x>=9&&x<31&&y>=9&&y<31),N,{glyph:'田'});
const ring=geometryFromMask(gen((x,y)=>x>=7&&x<33&&y>=7&&y<33&&!(x>=14&&x<26&&y>=14&&y<26)),N,{glyph:'回'});
const slash=geometryFromMask(gen((x,y)=>Math.abs(y-x-5)<2&&x>=5&&x<30),N,{glyph:'ノ'});
const p={x:0,y:0,angle:0,radius:.5};
assert.equal(containsWorld(ring,p,0,0),false);
assert.ok(outwardNormal(block,p,.3,0),'normal available on solid edge');
const contact=contactManifold({...p,x:0},{...p,x:.52,y:.2},block,ring);
assert.ok(contact,'shapes should overlap');
assert.ok(Number.isFinite(contact.nx)&&Number.isFinite(contact.ny));
assert.ok(Math.hypot(contact.nx,contact.ny)>.99);
const stats={speed:65,power:65,balance:65,maxHp:110,pointiness:.1};
function create(angle=0,stage='01-01') {return new ShapeSimulationV5({player:{glyph:'田',geometry:block,stats},enemy:{glyph:'回',geometry:ring,stats:{...stats,maxHp:80}},playerAction:{angle,power:.79,spinDirection:1},enemyLaunch:{angle:0,power:.72,spinDirection:-1},stage});}
const a=create(),b=create();a.runToEnd();b.runToEnd();
assert.deepEqual(a.snapshot(),b.snapshot(),'fixed input repeatable in same JS runtime');
assert.equal(a.result.simulationVersion,SHAPE_SIM_VERSION);assert.equal(a.result.rulesVersion,SHAPE_RULE_VERSION);
assert.ok(a.result.tick<=2700);assert.ok(a.result.geometryHashes.every(Boolean));
assert.ok(a.tops.every(t=>Number.isFinite(t.omega)&&Number.isFinite(t.angle)));
const variant=create(.6);variant.runToEnd();assert.notDeepEqual(a.result,variant.result,'angle influences battle outcome');
assert.equal(Object.keys(LEVEL_CATALOG).length,4);
assert.equal(isUnlocked('01-01',{}),true);assert.equal(isUnlocked('01-02',{}),false);
assert.equal(isUnlocked('01-02',{'01-01':{stars:1}}),true);
assert.equal(isUnlocked('02-01',{'01-04':{stars:3}}),false);
const result={winner:0,durationSeconds:11,hp:[110,0],spin:[76,0],playerMaxHp:110,ranked:false,simulationVersion:SHAPE_SIM_VERSION,rulesVersion:SHAPE_RULE_VERSION};
assert.equal(evaluateLevelResult(LEVEL_CATALOG['01-02'],result,{angle:0,power:.5}).cleared,false);
assert.equal(evaluateLevelResult(LEVEL_CATALOG['01-02'],result,{angle:0,power:.75}).stars,3);
assert.equal(evaluateLevelResult(LEVEL_CATALOG['01-03'],result,{angle:0,power:.75}).cleared,false);
assert.equal(evaluateLevelResult(LEVEL_CATALOG['01-03'],result,{angle:.25,power:.75}).cleared,true);
const st={items:new Map(),getItem(k){return this.items.get(k)||null;},setItem(k,v){this.items.set(k,v);}};
let save=emptySave();assert.throws(()=>commitBattle(save,{levelId:'01-02',result,action:{angle:0,power:.75}},st),/Locked/);
let c=commitBattle(save,{levelId:'01-01',result,action:{angle:0,power:.75}},st);
assert.equal(c.evaluation.stars,3);assert.equal(c.status,'saved');save=c.save;
assert.ok(isUnlocked('01-02',save.progress));
c=commitBattle(save,{levelId:'01-02',result,action:{angle:0,power:.5}},st);
assert.equal(c.evaluation.cleared,false);assert.equal(c.save.battleCount,2);save=c.save;
c=commitBattle(save,{levelId:'01-02',result,action:{angle:0,power:.75}},st);
save=c.save;assert.equal(c.save.progress['01-02'].stars,3);assert.ok(st.items.has(SAVE_KEY));assert.deepEqual(loadSave(st).save.progress,c.save.progress);
assert.throws(()=>commitBattle(save,{levelId:'01-03',result:{...result,simulationVersion:'old'},action:{angle:.25,power:.75}},st),/incompatible/);
const failing={getItem:k=>st.getItem(k),setItem(){throw Error('quota');}};
c=commitBattle(save,{levelId:'01-03',result,action:{angle:.25,power:.75}},failing);
assert.equal(c.status,'memory-only');assert.equal(loadSave(st).save.progress['01-03'],undefined);
assert.notEqual(SAVE_KEY,'moji-blade.v3.r4.local-save.v1');
console.log('R5 TESTS PASSED: shape manifold, finite angular response, deterministic replay, 4 level contracts, sequence unlock, objective/star rules and safe isolated save.');
